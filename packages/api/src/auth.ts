import { accounts, createDb, sessions, users, verifications } from '@project180/db'
import { betterAuth } from 'better-auth'
import { drizzleAdapter } from 'better-auth/adapters/drizzle'
import type { Bindings } from './env'

const DAY = 60 * 60 * 24

/**
 * Which app is signing in. Each has its own session cookie, so signing in to one never signs
 * you in to the other (on localhost both apps share cookies, because cookies ignore the port).
 */
export type AppKind = 'app' | 'admin'

/** The admin dev server tags its proxied /api calls with this header (apps/admin/vite.config.ts). */
export const APP_KIND_HEADER = 'x-project180-app'

/** The admin Worker (STAFF_ONLY) or a call from the admin dev server. Only ever narrows access. */
export function appKindOf(env: Bindings, headers: Headers): AppKind {
  return env.STAFF_ONLY === '1' || headers.get(APP_KIND_HEADER) === 'admin' ? 'admin' : 'app'
}

export function createAuth(env: Bindings, kind: AppKind = 'app') {
  return betterAuth({
    appName: 'Project 180',
    baseURL: env.BETTER_AUTH_URL,
    basePath: '/api/auth',
    secret: env.BETTER_AUTH_SECRET,
    trustedOrigins: [
      env.BETTER_AUTH_URL,
      ...(env.TRUSTED_ORIGINS?.split(',').map((o) => o.trim()) ?? []),
    ],
    database: drizzleAdapter(createDb(env.DB), {
      provider: 'sqlite',
      schema: { user: users, session: sessions, account: accounts, verification: verifications },
    }),
    emailAndPassword: {
      enabled: true,
      // No public sign-up: admins come from `bun run admin:create`, everyone else from an admin.
      disableSignUp: true,
      minPasswordLength: 8,
    },
    session: {
      // Sliding sessions: signed out after SESSION_DAYS without use (app 30, admin 7),
      // renewed at most once a day while in use. See wrangler.jsonc.
      expiresIn: (Number(env.SESSION_DAYS) || 30) * DAY,
      updateAge: DAY,
      // Which app the sign-in is for, shown with the person's devices in the admin.
      additionalFields: { app: { type: 'string', required: false, input: false } },
      // Trust the signed session cookie for a short while instead of reading the database on
      // every call (chat and lists refresh often). Off unless SESSION_CACHE_SECONDS is set.
      cookieCache:
        Number(env.SESSION_CACHE_SECONDS) > 0
          ? { enabled: true, maxAge: Number(env.SESSION_CACHE_SECONDS) }
          : undefined,
    },
    user: {
      additionalFields: {
        role: { type: 'string', input: false, defaultValue: 'member' },
        // Changed through PATCH /api/me (validated), never Better Auth's own update-user.
        timezone: {
          type: 'string',
          required: false,
          input: false,
          defaultValue: 'Africa/Johannesburg',
        },
        weightUnit: { type: 'string', required: false, input: false, defaultValue: 'kg' },
        coachId: { type: 'number', required: false, input: false },
        mustChangePassword: { type: 'boolean', required: false, input: false, defaultValue: false },
        lastSeenAt: { type: 'date', required: false, input: false },
        blockedAt: { type: 'date', required: false, input: false },
      },
    },
    databaseHooks: {
      session: { create: { before: async (session) => ({ data: { ...session, app: kind } }) } },
    },
    advanced: {
      // Auto-increment integer ids, generated by D1.
      database: { generateId: 'serial' },
      // The phone app keeps Better Auth's default name, so nobody on a phone is signed out.
      cookiePrefix: kind === 'admin' ? 'project180-admin' : 'better-auth',
    },
  })
}

export type Auth = ReturnType<typeof createAuth>
