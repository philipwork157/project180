/**
 * Adds "Philip's Workout" (a 4-week program and its five workouts) to the library.
 *
 *   bun run db:philip          local database
 *   bun run db:philip:dev      the Cloudflare dev environment's database
 *
 * Run the library seed first (bun run db:seed / db:seed:dev): the workouts use its exercises.
 * Safe to run again: a workout or program that already exists (by name) is left alone.
 * Everything is owned by the first owner. Assign it from the admin afterwards.
 */
import { spawnSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { EXERCISES, MOBILITY } from '../seed/exercises'
import { EXTRA_EXERCISES } from '../seed/exercises-extra'
import { MORE_EXERCISES } from '../seed/exercises-more'
import { PHILIP_PROGRAM, PHILIP_WORKOUTS } from '../seed/philip'

const dev =
  process.argv.includes('--env') && process.argv[process.argv.indexOf('--env') + 1] === 'dev'
const here = import.meta.dirname
const root = path.resolve(here, '../../..')
const appDir = path.join(root, 'apps/app')
const sqlFile = path.join(here, '../seed/philip.sql')

const q = (v: string | number | null) =>
  v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${v.replaceAll("'", "''")}'`
const now = Date.now()
const admin = `(SELECT id FROM users WHERE role IN ('owner', 'admin') ORDER BY role = 'owner' DESC, id LIMIT 1)`
const hasAdmin = `EXISTS (SELECT 1 FROM users WHERE role IN ('owner', 'admin'))`

// Catch typos before touching the database.
const known = new Set(
  [...EXERCISES, ...MORE_EXERCISES, ...EXTRA_EXERCISES, ...MOBILITY].map(([name]) =>
    name.toLowerCase(),
  ),
)
for (const w of PHILIP_WORKOUTS) {
  for (const r of w.rows) {
    if (!known.has(r.name.toLowerCase()))
      throw new Error(`Workout "${w.name}" uses unknown exercise "${r.name}"`)
    if (r.group !== null && !(r.group in w.supersets))
      throw new Error(`Workout "${w.name}": superset ${r.group} has no rounds`)
  }
}
const workoutNames = new Set(PHILIP_WORKOUTS.map((w) => w.name))
for (const d of PHILIP_PROGRAM.days) {
  if (!workoutNames.has(d.workout)) throw new Error(`Program day uses unknown "${d.workout}"`)
}

const exerciseId = (name: string) =>
  `(SELECT id FROM exercises WHERE lower(name) = lower(${q(name)}) AND business_id = (SELECT business_id FROM users WHERE id = ${admin}) ORDER BY archived_at IS NOT NULL, id LIMIT 1)`
// Library rows only (client_id IS NULL): clients' copies carry the same names.
const workoutId = (name: string) =>
  `(SELECT id FROM workouts WHERE name = ${q(name)} AND client_id IS NULL ORDER BY id LIMIT 1)`
const programId = `(SELECT id FROM programs WHERE name = ${q(PHILIP_PROGRAM.name)} AND client_id IS NULL ORDER BY id LIMIT 1)`

const sql: string[] = ['-- Generated by packages/db/scripts/seed-philip.ts. Safe to run again.']

for (const w of PHILIP_WORKOUTS) {
  // Rows and supersets are only added when this run created the workout (same timestamp),
  // so a workout you've since edited is never changed.
  const createdNow = `EXISTS (SELECT 1 FROM workouts WHERE name = ${q(w.name)} AND client_id IS NULL AND created_at = ${now})`
  sql.push(
    `INSERT INTO workouts (name, description, estimated_minutes, created_by, created_at, updated_at)
SELECT ${q(w.name)}, ${q(w.description)}, ${w.minutes}, ${admin}, ${now}, ${now}
WHERE ${hasAdmin} AND NOT EXISTS (SELECT 1 FROM workouts WHERE name = ${q(w.name)} AND client_id IS NULL);`,
  )
  w.rows.forEach((r, position) => {
    sql.push(
      `INSERT INTO workout_exercises (workout_id, exercise_id, position, target_sets, target_reps_min, target_reps_max, target_seconds, rest_seconds, section, target_hr_zone, superset_group, notes)
SELECT ${workoutId(w.name)}, ${exerciseId(r.name)}, ${position}, ${r.sets}, ${q(r.repsMin)}, ${q(r.repsMax)}, ${q(r.seconds)}, ${r.rest}, ${q(r.section)}, ${q(r.hrZone)}, ${q(r.group)}, ${q(r.notes)}
WHERE ${createdNow};`,
    )
  })
  for (const [group, rounds] of Object.entries(w.supersets)) {
    sql.push(
      `INSERT INTO workout_groups (workout_id, group_number, kind, rounds)
SELECT ${workoutId(w.name)}, ${Number(group)}, 'superset', ${rounds}
WHERE ${createdNow};`,
    )
  }
}

const programCreatedNow = `EXISTS (SELECT 1 FROM programs WHERE name = ${q(PHILIP_PROGRAM.name)} AND client_id IS NULL AND created_at = ${now})`
sql.push(
  `INSERT INTO programs (name, description, duration_weeks, created_by, created_at, updated_at)
SELECT ${q(PHILIP_PROGRAM.name)}, ${q(PHILIP_PROGRAM.description)}, ${PHILIP_PROGRAM.durationWeeks}, ${admin}, ${now}, ${now}
WHERE ${hasAdmin} AND NOT EXISTS (SELECT 1 FROM programs WHERE name = ${q(PHILIP_PROGRAM.name)} AND client_id IS NULL);`,
)
for (const d of PHILIP_PROGRAM.days) {
  sql.push(
    `INSERT INTO program_days (program_id, week_number, day_number, workout_id, checkin_required, notes)
SELECT ${programId}, ${d.weekNumber}, ${d.dayNumber}, ${workoutId(d.workout)}, ${d.checkinRequired ? 1 : 0}, ${q(d.notes)}
WHERE ${programCreatedNow};`,
  )
}

writeFileSync(sqlFile, `${sql.join('\n\n')}\n`)
console.log(
  `${PHILIP_PROGRAM.name}: ${PHILIP_WORKOUTS.length} workouts, ${PHILIP_PROGRAM.days.length} training days → ${dev ? 'Cloudflare DEV' : 'local'} database`,
)

const args = [
  'wrangler',
  'd1',
  'execute',
  dev ? 'project180-db-dev' : 'project180-db',
  dev ? '--remote' : '--local',
  ...(dev ? ['--env', 'dev'] : ['--persist-to', path.join(root, '.wrangler/state')]),
  '--file',
  sqlFile,
  '--yes',
]
const result = spawnSync('bunx', args, { cwd: appDir, stdio: 'inherit' })
if (result.status !== 0) process.exit(result.status ?? 1)

console.log(
  '\nDone. Open Programs in the admin and assign it. If nothing appeared, create an admin and run the library seed first.',
)
