/**
 * Adds the starter recipes (packages/db/seed/recipes.ts).
 *
 *   bun run db:recipes          local database (bun run dev)
 *   bun run db:recipes:dev      the Cloudflare dev environment's database
 *   bun run db:recipes:remote   live D1 database on Cloudflare
 *
 * Add `-- --business "Starter library"` to fill one business by its exact name; without it,
 * the first owner's business.
 *
 * Safe to run again: a recipe whose name already exists is skipped, so nothing you've changed
 * is touched. Owned by the first owner, so create your account (and run migrations) first.
 *
 * Photos: a recipe's `image` (a file in apps/app/public/recipe-images) is added to recipes
 * that have no photo yet. A photo a coach uploaded, or removed on purpose, is never replaced.
 */
import { spawnSync } from 'node:child_process'
import { existsSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { recipeInput } from '@project180/shared'
import { RECIPES } from '../seed/recipes'
import { seedTarget } from './target'

const dev =
  process.argv.includes('--env') && process.argv[process.argv.indexOf('--env') + 1] === 'dev'
const remote = dev || process.argv.includes('--remote')
const root = path.resolve(import.meta.dirname, '../../..')

const q = (v: string | number | null) =>
  v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${v.replaceAll("'", "''")}'`
const now = Date.now()
// The business to fill (--business "Name", or the first owner's), owned by its first owner.
const target = seedTarget(process.argv)
const { admin, business, hasAdmin, inBusiness } = target

const sql: string[] = ['-- Generated by packages/db/scripts/seed-recipes.ts. Safe to run again.']
const titles = new Set<string>()
const photos = path.join(root, 'apps/app/public/recipe-images')
let withPhotos = 0

/** A bundled photo file, or a free Unsplash photo's image address. */
function photoKey(title: string, image: string | undefined): string | null {
  if (!image) return null
  if (/^https:\/\/images\.unsplash\.com\/photo-[\w-]+$/.test(image)) return image
  if (/^[\w.-]+\.(webp|jpg|png)$/.test(image) && existsSync(path.join(photos, image)))
    return `recipe-images/${image}`
  throw new Error(`"${title}": no photo apps/app/public/recipe-images/${image}`)
}
for (const raw of RECIPES) {
  // The same checks the API makes, so a typo never reaches the database.
  const r = recipeInput.parse(raw)
  if (titles.has(r.title.toLowerCase())) throw new Error(`"${r.title}" is in the list twice`)
  titles.add(r.title.toLowerCase())
  const imageKey = photoKey(r.title, raw.image)
  sql.push(
    `INSERT INTO recipes (title, summary, meal, category, servings, prep_minutes, cook_minutes, kcal, protein_g, carbs_g, fat_g, ingredients, steps, tips, source_name, source_url, image_key, created_by, business_id, created_at, updated_at)
SELECT ${q(r.title)}, ${q(r.summary)}, ${q(r.meal)}, ${q(r.category)}, ${r.servings}, ${r.prepMinutes}, ${r.cookMinutes}, ${r.kcal}, ${r.proteinG}, ${q(r.carbsG)}, ${q(r.fatG)}, ${q(JSON.stringify(r.ingredients))}, ${q(JSON.stringify(r.steps))}, ${q(r.tips)}, ${q(r.sourceName)}, ${q(r.sourceUrl)}, ${q(imageKey)}, ${admin}, ${business}, ${now}, ${now}
WHERE ${hasAdmin} AND NOT EXISTS (SELECT 1 FROM recipes WHERE lower(title) = lower(${q(r.title)}) AND ${inBusiness});`,
  )
  if (imageKey) {
    withPhotos += 1
    // Recipes added before they had a photo get it now (never over a coach's own or 'none').
    sql.push(
      `UPDATE recipes SET image_key = ${q(imageKey)} WHERE lower(title) = lower(${q(r.title)}) AND image_key IS NULL AND ${inBusiness};`,
    )
  }
}

const dir = mkdtempSync(path.join(tmpdir(), 'p180-recipes-'))
const file = path.join(dir, 'recipes.sql')
writeFileSync(file, `${sql.join('\n\n')}\n`)
console.log(
  `Recipes: ${titles.size} (${withPhotos} with photos) → ${target.label}, ${dev ? 'Cloudflare DEV' : remote ? 'LIVE (remote)' : 'local'} database`,
)
const args = [
  'wrangler',
  'd1',
  'execute',
  dev ? 'project180-db-dev' : 'project180-db',
  remote ? '--remote' : '--local',
  ...(dev ? ['--env', 'dev'] : []),
  ...(remote ? [] : ['--persist-to', path.join(root, '.wrangler/state')]),
  '--file',
  file,
  '--yes',
]
const result = spawnSync('bunx', args, { cwd: path.join(root, 'apps/app'), stdio: 'inherit' })
rmSync(dir, { recursive: true, force: true })
if (result.status !== 0) process.exit(result.status ?? 1)
