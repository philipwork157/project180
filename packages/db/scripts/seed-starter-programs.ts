/**
 * Adds the ready-made starter programs (Beginner Full Body, Push Pull Legs 3 and 6 days, Upper
 * Lower, Fat Loss) and their workouts to the starter library: what people training on their
 * own see on Today and can start.
 *
 *   bun run db:starter            local database
 *   bun run db:starter:dev        the Cloudflare dev environment's database
 *   bun run db:starter:remote     live D1 database on Cloudflare
 *
 * Fills the business picked as the starter library on the Platform page. Add
 * `-- --business "Name"` to fill another business by its exact name instead.
 * Run the library seed for that business first (its exercises are used), e.g.
 * `bun run db:seed -- --business "Starter library"`.
 * Safe to run again: a workout or program that already exists there (by name) is left alone, so
 * anything you've edited is never changed. Owned by that business's first owner (or coach).
 */
import { spawnSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { EXERCISES, MOBILITY } from '../seed/exercises'
import { ENDURANCE_EXERCISES } from '../seed/exercises-endurance'
import { EXTRA_EXERCISES } from '../seed/exercises-extra'
import { MORE_EXERCISES } from '../seed/exercises-more'
import { STARTER_PROGRAMS, STARTER_WORKOUTS } from '../seed/starter-programs'
import { seedTarget } from './target'

const dev =
  process.argv.includes('--env') && process.argv[process.argv.indexOf('--env') + 1] === 'dev'
const remote = dev || process.argv.includes('--remote')
const here = import.meta.dirname
const root = path.resolve(here, '../../..')
const appDir = path.join(root, 'apps/app')
const sqlFile = path.join(here, '../seed/starter-programs.sql')

const q = (v: string | number | null) =>
  v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${v.replaceAll("'", "''")}'`
const now = Date.now()

// The starter library (Platform page) unless --business names another one.
const target = process.argv.includes('--business') ? seedTarget(process.argv) : starterTarget()
const { admin, hasAdmin, inBusiness, workoutsOfBusiness } = target

function starterTarget() {
  const business = `(SELECT CAST(value AS INTEGER) FROM app_settings WHERE key = 'starter_business_id')`
  const staff = `role IN ('owner', 'admin') AND business_id = ${business}`
  return {
    label: 'the starter library',
    admin: `(SELECT id FROM users WHERE ${staff} ORDER BY role = 'owner' DESC, id LIMIT 1)`,
    hasAdmin: `EXISTS (SELECT 1 FROM users WHERE ${staff})`,
    inBusiness: `business_id = ${business}`,
    workoutsOfBusiness: `client_id IS NULL AND created_by IN (SELECT id FROM users WHERE ${staff})`,
  }
}

// Catch typos before touching the database.
const known = new Set(
  [...EXERCISES, ...MORE_EXERCISES, ...EXTRA_EXERCISES, ...ENDURANCE_EXERCISES, ...MOBILITY].map(
    ([name]) => name.toLowerCase(),
  ),
)
const workoutNames = new Set<string>()
for (const w of STARTER_WORKOUTS) {
  if (workoutNames.has(w.name)) throw new Error(`Workout "${w.name}" is listed twice`)
  workoutNames.add(w.name)
  for (const r of w.rows) {
    if (!known.has(r.name.toLowerCase()))
      throw new Error(`Workout "${w.name}" uses unknown exercise "${r.name}"`)
  }
}
for (const p of STARTER_PROGRAMS) {
  if (p.weekNotes.length !== p.durationWeeks)
    throw new Error(`"${p.name}" needs one week note per week`)
  for (const d of p.week) {
    if (!workoutNames.has(d.workout)) throw new Error(`"${p.name}" uses unknown "${d.workout}"`)
    if (d.day < 1 || d.day > 7) throw new Error(`"${p.name}": day ${d.day} isn't 1–7`)
  }
}

const exerciseId = (name: string) =>
  `(SELECT id FROM exercises WHERE lower(name) = lower(${q(name)}) AND ${inBusiness} ORDER BY archived_at IS NOT NULL, id LIMIT 1)`
// Library rows of that business only: clients' copies and other businesses share names.
const workoutId = (name: string) =>
  `(SELECT id FROM workouts WHERE name = ${q(name)} AND ${workoutsOfBusiness} ORDER BY id LIMIT 1)`
const programsOfBusiness = workoutsOfBusiness
const programId = (name: string) =>
  `(SELECT id FROM programs WHERE name = ${q(name)} AND ${programsOfBusiness} ORDER BY id LIMIT 1)`

const sql: string[] = [
  '-- Generated by packages/db/scripts/seed-starter-programs.ts. Safe to run again.',
]

for (const w of STARTER_WORKOUTS) {
  // Rows are only added when this run created the workout (same timestamp), so a workout
  // you've since edited is never changed.
  const createdNow = `EXISTS (SELECT 1 FROM workouts WHERE name = ${q(w.name)} AND ${workoutsOfBusiness} AND created_at = ${now})`
  sql.push(
    `INSERT INTO workouts (name, description, estimated_minutes, created_by, created_at, updated_at)
SELECT ${q(w.name)}, ${q(w.description)}, ${w.minutes}, ${admin}, ${now}, ${now}
WHERE ${hasAdmin} AND NOT EXISTS (SELECT 1 FROM workouts WHERE name = ${q(w.name)} AND ${workoutsOfBusiness});`,
  )
  w.rows.forEach((r, position) => {
    sql.push(
      `INSERT INTO workout_exercises (workout_id, exercise_id, position, target_sets, target_reps_min, target_reps_max, target_seconds, rest_seconds, section, target_hr_zone, target_rpe, notes)
SELECT ${workoutId(w.name)}, ${exerciseId(r.name)}, ${position}, ${r.sets}, ${q(r.repsMin)}, ${q(r.repsMax)}, ${q(r.seconds)}, ${r.rest}, ${q(r.section)}, ${q(r.hrZone)}, ${q(r.rpe)}, ${q(r.notes)}
WHERE ${createdNow} AND ${exerciseId(r.name)} IS NOT NULL;`,
    )
  })
}

for (const p of STARTER_PROGRAMS) {
  const createdNow = `EXISTS (SELECT 1 FROM programs WHERE name = ${q(p.name)} AND ${programsOfBusiness} AND created_at = ${now})`
  sql.push(
    `INSERT INTO programs (name, description, duration_weeks, created_by, created_at, updated_at)
SELECT ${q(p.name)}, ${q(p.description)}, ${p.durationWeeks}, ${admin}, ${now}, ${now}
WHERE ${hasAdmin} AND NOT EXISTS (SELECT 1 FROM programs WHERE name = ${q(p.name)} AND ${programsOfBusiness});`,
  )
  p.weekNotes.forEach((note, i) => {
    for (const d of p.week) {
      sql.push(
        `INSERT INTO program_days (program_id, week_number, day_number, workout_id, checkin_required, notes)
SELECT ${programId(p.name)}, ${i + 1}, ${d.day}, ${workoutId(d.workout)}, ${d === p.week[0] ? 1 : 0}, ${q(note)}
WHERE ${createdNow};`,
      )
    }
  })
}

writeFileSync(sqlFile, `${sql.join('\n\n')}\n`)
console.log(
  `Starter programs: ${STARTER_PROGRAMS.length} programs, ${STARTER_WORKOUTS.length} workouts → ${target.label}, ${dev ? 'Cloudflare DEV' : remote ? 'LIVE (remote)' : 'local'} database`,
)

const args = [
  'wrangler',
  'd1',
  'execute',
  dev ? 'project180-db-dev' : 'project180-db',
  remote ? '--remote' : '--local',
  ...(dev ? ['--env', 'dev'] : []),
  ...(remote ? [] : ['--persist-to', path.join(root, '.wrangler/state')]),
  '--file',
  sqlFile,
  '--yes',
]
const result = spawnSync('bunx', args, { cwd: appDir, stdio: 'inherit' })
if (result.status !== 0) process.exit(result.status ?? 1)

console.log(
  '\nDone. Existing programs were left alone. If nothing appeared: pick the starter library on the Platform page (it needs an owner or coach) and run its library seed first.',
)
