type RandomFill = (bytes: Uint8Array) => Uint8Array

// Our buffers are never shared, so the narrower type Web Crypto asks for is safe.
const cryptoFill: RandomFill = (bytes) => crypto.getRandomValues(bytes as Uint8Array<ArrayBuffer>)

/** A number from 100 to 999, without modulo bias (rejects the top of the 16-bit range). */
function threeDigits(fill: RandomFill): number {
  const limit = 65536 - (65536 % 900)
  for (;;) {
    const [hi = 0, lo = 0] = fill(new Uint8Array(2))
    const n = (hi << 8) | lo
    if (n < limit) return 100 + (n % 900)
  }
}

/** A fresh temporary password, e.g. "Tempo-Cedar-Otter-Kayak-482". */
export function generateTempPassword(fill: RandomFill = cryptoFill): string {
  const cap = (w: string) => w.charAt(0).toUpperCase() + w.slice(1)
  const words = [...fill(new Uint8Array(4))].map((b) => cap(TEMP_PASSWORD_WORDS[b] ?? 'lift'))
  return `${words.join('-')}-${threeDigits(fill)}`
}

/** True once a temporary password set at `setAt` is too old to sign in with. */
export function tempPasswordExpired(setAt: Date, now = Date.now()): boolean {
  return now - setAt.getTime() > TEMP_PASSWORD_DAYS * 24 * 60 * 60 * 1000
}
